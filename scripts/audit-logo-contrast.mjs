/**
 * SMA-93: audit `public/logos/*.svg` for marks that disappear on light cards.
 *
 * A logo is flagged "light-monochrome" when every paint it uses is a
 * near-white neutral (high lightness, near-zero chroma). Those marks are
 * invisible on white cards and safe to `filter: invert(1)` in light mode —
 * inverting a neutral only flips lightness, so the mark stays on-brand
 * (white -> black). Logos with any chromatic paint are skipped: invert would
 * shift their hue, and recoloring brands is out of scope.
 *
 * Usage:
 *   node scripts/audit-logo-contrast.mjs          # report to stdout
 *   node scripts/audit-logo-contrast.mjs --write  # regenerate lib/light-logo-ids.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const logosDir = join(root, "public", "logos")
const generatedPath = join(root, "lib", "light-logo-ids.ts")

const NAMED = {
  white: "#ffffff",
  black: "#000000",
  none: null,
  transparent: null,
  currentcolor: null, // never used with a light context in this app
}

function parseColor(raw) {
  const value = raw.trim().toLowerCase()
  if (value in NAMED) {
    return NAMED[value] === null ? null : parseColor(NAMED[value])
  }
  let hex = value.match(/^#([0-9a-f]{3})$/)?.[1]
  if (hex) {
    return hex.split("").map((c) => parseInt(c + c, 16))
  }
  hex = value.match(/^#([0-9a-f]{6})([0-9a-f]{2})?$/)?.[1]
  if (hex) {
    return [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16))
  }
  const rgb = value.match(/^rgba?\(\s*(\d+)[,\s]+(\d+)[,\s]+(\d+)/)
  if (rgb) {
    return [Number(rgb[1]), Number(rgb[2]), Number(rgb[3])]
  }
  return "unparsed"
}

/** Near-white neutral: bright with almost no chroma, e.g. #fff, #f1f0ec. */
function isLightNeutral([r, g, b]) {
  return Math.min(r, g, b) >= 190 && Math.max(r, g, b) - Math.min(r, g, b) <= 32
}

function extractPaints(svg) {
  const paints = []
  for (const match of svg.matchAll(
    /(?:fill|stroke|stop-color|flood-color)\s*[:=]\s*["']?([^"';)}\s]+)/g
  )) {
    paints.push(match[1])
  }
  return paints.filter((p) => !p.startsWith("url("))
}

const results = []
for (const file of readdirSync(logosDir).sort()) {
  if (!file.endsWith(".svg")) continue
  const id = file.replace(/\.svg$/, "")
  const svg = readFileSync(join(logosDir, file), "utf8")
  const colors = extractPaints(svg)
    .map(parseColor)
    .filter((c) => c !== null)
  if (colors.length === 0) {
    // No explicit paint => SVG default black; fine on light, broken on dark.
    results.push({ id, verdict: "no-paint" })
    continue
  }
  if (colors.includes("unparsed")) {
    results.push({ id, verdict: "unparsed" })
    continue
  }
  results.push({
    id,
    verdict: colors.every(isLightNeutral) ? "light-monochrome" : "keeps-color",
  })
}

const lightIds = results
  .filter((r) => r.verdict === "light-monochrome")
  .map((r) => r.id)
const problems = results.filter(
  (r) => r.verdict === "unparsed" || r.verdict === "no-paint"
)

console.log(`${results.length} logos audited`)
console.log(`${lightIds.length} light-monochrome (invert in light mode):`)
console.log(lightIds.join(", "))
if (problems.length > 0) {
  console.log("\nNeeds manual review:")
  for (const p of problems) console.log(`  ${p.id}: ${p.verdict}`)
}

if (process.argv.includes("--write")) {
  const banner = `/**
 * Generated by \`node scripts/audit-logo-contrast.mjs --write\` (SMA-93).
 * Do not edit by hand; rerun the audit after adding or changing logos.
 *
 * Service logos whose SVG is entirely near-white neutral. They are drawn for
 * the dark board and vanish on light cards, so light mode renders them with
 * \`filter: invert(1)\` (see LIGHT_LOGO_INVERT_CLASS). Chromatic logos are
 * excluded: invert would shift their brand hue.
 */
`
  const body = `export const LIGHT_LOGO_IDS: ReadonlySet<string> = new Set([
${lightIds.map((id) => `  "${id}",`).join("\n")}
])

/** Tailwind classes that flip a white mark to black on light surfaces only. */
export const LIGHT_LOGO_INVERT_CLASS = "invert dark:invert-0"

export function logoInvertClass(id: string): string | false {
  return LIGHT_LOGO_IDS.has(id) && LIGHT_LOGO_INVERT_CLASS
}
`
  writeFileSync(generatedPath, banner + body)
  console.log(`\nWrote ${generatedPath}`)
}
